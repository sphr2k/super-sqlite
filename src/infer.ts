/** Deterministic, build-time schema inference from representative JSON records. */
type Scalar = 'string' | 'number' | 'boolean' | 'null' | 'unknown';
export type Shape =
  | { kind: Scalar }
  | { kind: 'array'; item: Shape | null }
  | { kind: 'object'; count: number; fields: Record<string, { count: number; value: Shape }> }
  | { kind: 'union'; options: Shape[] };

const scalar = (kind: Scalar): Shape => ({ kind });

function shapeOf(value: unknown): Shape {
  if (value === null) return scalar('null');
  if (Array.isArray(value)) return { kind: 'array', item: value.reduce<Shape | null>((acc, val) => merge(acc, shapeOf(val)), null) };
  if (typeof value === 'object') {
    return { kind: 'object', count: 1, fields: Object.fromEntries(
      Object.entries(value as Record<string, unknown>).map(([key, val]) => [key, { count: 1, value: shapeOf(val) }])
    ) };
  }
  if (typeof value === 'string' || typeof value === 'boolean') return scalar(typeof value as Scalar);
  if (typeof value === 'number') return Number.isFinite(value) ? scalar('number') : scalar('unknown');
  return scalar('unknown');
}

function merge(a: Shape | null, b: Shape): Shape {
  if (!a) return b;
  const optionsA = a.kind === 'union' ? a.options : [a];
  const optionsB = b.kind === 'union' ? b.options : [b];
  const options: Shape[] = [...optionsA];
  for (const next of optionsB) {
    const index = options.findIndex(p => p.kind === next.kind);
    if (index < 0) { options.push(next); continue; }
    const previous = options[index];
    if (previous.kind === 'array' && next.kind === 'array') {
      options[index] = { kind: 'array', item: next.item ? merge(previous.item, next.item) : previous.item };
    } else if (previous.kind === 'object' && next.kind === 'object') {
      const fields: typeof previous.fields = Object.assign(Object.create(null), previous.fields);
      for (const [key, val] of Object.entries(next.fields)) {
        const old = fields[key];
        fields[key] = old ? { count: old.count + val.count, value: merge(old.value, val.value) } : val;
      }
      options[index] = { kind: 'object', count: previous.count + next.count, fields };
    }
  }
  return options.length === 1 ? options[0] : { kind: 'union', options };
}

export function inferJsonShape(records: readonly unknown[]): Shape {
  if (!records.length) throw new Error('Cannot infer schema from an empty dataset');
  return records.reduce<Shape | null>((acc, value) => merge(acc, shapeOf(value)), null)!;
}

function render(shape: Shape, depth = 0): string {
  const indent = '  '.repeat(depth);
  const next = '  '.repeat(depth + 1);
  if (shape.kind === 'object') {
    const fields = Object.entries(shape.fields).sort(([a], [b]) => a.localeCompare(b));
    if (fields.some(([key]) => key === '__proto__')) throw new Error('Unsafe JSON property name: __proto__');
    if (!fields.length) return '{}';
    return `{\n${fields.map(([key, val]) =>
      `${next}${JSON.stringify(val.count < shape.count ? key + '?' : key)}: ${render(val.value, depth + 1)}`
    ).join(',\n')}\n${indent}}`;
  }
  if (shape.kind === 'array') {
    if (!shape.item) return JSON.stringify('unknown[]');
    if (shape.item.kind === 'object' || shape.item.kind === 'array') {
      return `type(${render(shape.item, depth)}).array()`;
    }
    if (shape.item.kind === 'union' && shape.item.options.some(o => o.kind === 'object' || o.kind === 'array')) {
      return JSON.stringify('unknown[]');
    }
    const member = shape.item.kind === 'union' ? shape.item.options.map(o => o.kind).join(' | ') : shape.item.kind;
    return shape.item.kind === 'union' ? `type(${JSON.stringify(member)}).array()` : JSON.stringify(`${member}[]`);
  }
  if (shape.kind === 'union') {
    if (shape.options.some(o => o.kind === 'object' || o.kind === 'array')) {
      return JSON.stringify('unknown');
    }
    return JSON.stringify(shape.options.map(o => o.kind).sort().join(' | '));
  }
  return JSON.stringify(shape.kind);
}

export function generateArkTypeSource(name: string, shape: Shape): string {
  if (!/^[A-Za-z_$][\w$]*$/.test(name)) throw new Error('Invalid TypeScript export name');
  // The expected input is an object per record.
  if (shape.kind !== 'object') throw new Error('Expected JSON object records');
  return `// Generated by super-sqlite infer; review before committing.\nimport { type } from 'arktype';\n\nexport const ${name} = type(${render(shape)});\nexport type ${name} = typeof ${name}.infer;\n`;
}
